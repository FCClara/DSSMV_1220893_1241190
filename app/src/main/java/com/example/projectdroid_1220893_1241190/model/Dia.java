package com.example.projectdroid_1220893_1241190.model;

public class Dia {
    private String id;
    private String dia;

    public Dia(String id, String dia) {
        this.id = id;
        this.dia = dia;
    }

    public String getId() {
        return id;
    }

    public void setId(String id) {
        this.id = id;
    }

    public String getDia() {
        return dia;
    }

    public void setDia(String dia) {
        this.dia = dia;
    }
}
